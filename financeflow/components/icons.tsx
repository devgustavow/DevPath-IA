/** Ícone por nome (usado em categorias/contas armazenadas como string) */
export function Icon({
  name,
  className,
  style,
}: {
  name: string;
  className?: string;
  style?: React.CSSProperties;
}) {
  const Cmp = ICON_MAP[name] ?? CircleEllipsis;
  return <Cmp className={className} style={style} aria-hidden />;
}

